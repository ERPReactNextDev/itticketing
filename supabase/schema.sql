-- Atomically reserves the next sequence for a ticket-number day bucket.
create or replace function public.next_ticket_seq(p_date_key text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  v_seq bigint;
begin
  insert into public.ticket_counters (date_key, seq, updated_at)
  values (p_date_key, 1, now())
  on conflict (date_key)
  do update set seq = public.ticket_counters.seq + 1, updated_at = now()
  returning seq into v_seq;
  return v_seq;
end;
$$;

-- Atomically increments a fixed-window rate-limit bucket and returns the hits.
create or replace function public.consume_rate_limit(p_key text, p_window_start bigint)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_hits integer;
begin
  insert into public.rate_limits (key, window_start, total_hits)
  values (p_key, p_window_start, 1)
  on conflict (key, window_start)
  do update set total_hits = public.rate_limits.total_hits + 1
  returning total_hits into v_hits;
  return v_hits;
end;
$$;

-- Open-ticket load per technician, used by round-robin assignment.
create or replace function public.ticket_counts_by_technician()
returns table (technician_id text, open_count bigint)
language sql
security definer
set search_path = public
as $$
  select t.technician_id, count(*)::bigint as open_count
  from public.tickets t
  where t.technician_id is not null
    and lower(coalesce(t.status, '')) not in ('resolved', 'closed', 'cancelled', 'canceled')
  group by t.technician_id;
$$;

-- Appends one remark to a ticket's timeline.
--
-- PostgREST has no `$push`, and a read-modify-write in JS would lose a remark
-- whenever two events (a note plus an inbound email, say) land together. This
-- does the append in a single statement so concurrent writers cannot clobber
-- each other.
create or replace function public.append_ticket_remark(p_ticket_id bigint, p_remark jsonb)
returns void
language sql
security definer
set search_path = public
as $$
  update public.tickets
     set remarks_json = coalesce(remarks_json, '[]'::jsonb) || jsonb_build_array(p_remark),
         last_activity_at = now()
   where id = p_ticket_id;
$$;

-- Records an inbound/outbound message id on a ticket and links the thread.
--
-- The message id is appended only when it is not already present, and the
-- thread id is filled in only while it is still empty - so a ticket threads
-- onto the first conversation that reaches it and never gets re-pointed.
create or replace function public.thread_ticket_email(
  p_ticket_id bigint,
  p_message_id text,
  p_thread_id text default null
)
returns void
language sql
security definer
set search_path = public
as $$
  update public.tickets
     set email_message_ids =
           case
             when p_message_id is null or p_message_id = '' then coalesce(email_message_ids, '[]'::jsonb)
             when coalesce(email_message_ids, '[]'::jsonb) ? p_message_id then coalesce(email_message_ids, '[]'::jsonb)
             else coalesce(email_message_ids, '[]'::jsonb) || jsonb_build_array(p_message_id)
           end,
         email_thread_id = coalesce(email_thread_id, nullif(p_thread_id, '')),
         last_activity_at = now()
   where id = p_ticket_id;
$$;

