-- Derived columns kept in sync by Postgres itself. PostgREST cannot evaluate
-- `sla_due_at + paused_seconds` or `priority->>'slaHours'` in a filter, so both
-- values are materialised here instead: `sla_effective_due_at` powers the
-- "breached only" filter and `priority_sla_hours` powers priority sorting.
alter table public.tickets add column if not exists priority_sla_hours numeric
  generated always as (nullif(priority_data ->> 'slaHours', '')::numeric) stored;

alter table public.tickets add column if not exists sla_effective_due_at timestamptz
  generated always as (
    case
      when sla_due_at is null then null
      -- `timestamptz + interval` is STABLE (it depends on the session TimeZone
      -- for DST), which a generated column forbids. Round-tripping through UTC
      -- turns it into a plain `timestamp + interval` addition, which is
      -- IMMUTABLE and equivalent here because the pause is whole seconds.
      else (
        ((sla_due_at at time zone 'UTC')
          + make_interval(secs => coalesce(sla_paused_total_seconds, 0))) at time zone 'UTC'
      )
    end
  ) stored;

